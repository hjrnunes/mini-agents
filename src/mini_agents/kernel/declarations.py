"""Generate each domain's declaration files from its live server and slot table.

A consumer describes a target by two files, as it describes a declared one:
``tools-list.json``, the MCP ``tools/list`` result of the target's server, and
``runtime-spec.yaml`` (``declared-runtime-v1``), what that list does not state.
The spec names each seed slot, with its carrier tool, record key, field,
controller, content kind, ``max_chars`` and records, and classifies every
listed tool as ``read_only`` or ``mutating`` from the domain's
``TOOL_ACCESS``, since no tool carries MCP annotations. Beside them,
``value-facts.json`` holds the domain's ``VALUE_FACTS``
(:mod:`mini_agents.kernel.value_facts`), the record kind or date format of
tool arguments and ledger values, which a scanner reads with ``--value-facts``.

Each domain has two variants, each a target of its own:
``declarations/<domain>/safe/`` and ``declarations/<domain>/unsafe/``
(``--unsafe``). They list the same tools; their slots list the records each
executor returns. Both describe the default server, so the state summary,
hidden from ``tools/list``, is in neither.

The spec is written as JSON, which YAML reads unchanged, under a comment. Run
``scripts/gen_declarations.py`` after a tool, its description or arguments, a
seed slot, a ``TOOL_ACCESS`` entry or a value fact changes.
``tests/test_declarations.py`` fails while a committed file differs.
"""

from __future__ import annotations

import asyncio
import importlib
import json
from pathlib import Path
from typing import Any

from mcp.shared.memory import create_connected_server_and_client_session

from mini_agents.kernel import mcp_server

DECLARATIONS_DIR = Path(__file__).resolve().parent.parent / "declarations"
VARIANTS = ("safe", "unsafe")
TOOLS_LIST_FILE = "tools-list.json"
RUNTIME_SPEC_FILE = "runtime-spec.yaml"
VALUE_FACTS_FILE = "value-facts.json"
RUNTIME_SPEC_VERSION = "declared-runtime-v1"
OPERATION_CLASSES = {"read": "read_only", "write": "mutating"}

_SPEC_HEADER = (
    "# Generated by scripts/gen_declarations.py from the {domain} seed slots and\n"
    "# tool access table ({variant} variant); do not edit. declared-runtime-v1,\n"
    "# written as JSON, which YAML reads unchanged.\n"
)


def declaration_dir(domain: str, variant: str) -> Path:
    return DECLARATIONS_DIR / domain / variant


def build_server(domain: str, variant: str) -> Any:
    """Build the domain's default server for one variant, as ``main`` would."""
    unsafe = variant == "unsafe"
    previous = mcp_server.UNSAFE_MODE
    mcp_server.UNSAFE_MODE = unsafe
    try:
        return mcp_server.BUILDERS[domain]()
    finally:
        mcp_server.UNSAFE_MODE = previous


async def list_tools(server: Any) -> dict[str, Any]:
    """Return the ``tools/list`` result a client of ``server`` receives."""
    async with create_connected_server_and_client_session(server) as client:
        result = await client.list_tools()
    return result.model_dump(mode="json", by_alias=True, exclude_none=True)


def tools_list(domain: str, variant: str) -> dict[str, Any]:
    return asyncio.run(list_tools(build_server(domain, variant)))


def runtime_spec(domain: str, variant: str) -> dict[str, Any]:
    seeds = importlib.import_module(f"mini_agents.domains.{domain}.seeds")
    unsafe = variant == "unsafe"
    listed = [tool["name"] for tool in tools_list(domain, variant)["tools"]]
    operations: dict[str, list[str]] = {kind: [] for kind in OPERATION_CLASSES.values()}
    for name in listed:
        operations[OPERATION_CLASSES[seeds.TOOL_ACCESS[name]]].append(name)
    return {
        "schema_version": RUNTIME_SPEC_VERSION,
        "seed_slots": [
            {
                "id": slot.id,
                "carrier_operation": slot.carrier_operation,
                "record_key": slot.record_key,
                "field": slot.field,
                "controller": slot.controller,
                "content_kind": slot.content_kind,
                "max_chars": slot.max_chars,
                "records": list(slot.accepted(unsafe)),
            }
            for slot in seeds.SLOTS
        ],
        "operations": operations,
    }


def render_tools_list(domain: str, variant: str) -> str:
    return json.dumps(tools_list(domain, variant), indent=2) + "\n"


def render_runtime_spec(domain: str, variant: str) -> str:
    header = _SPEC_HEADER.format(domain=domain, variant=variant)
    return header + json.dumps(runtime_spec(domain, variant), indent=2) + "\n"


def value_facts(domain: str) -> dict[str, Any]:
    """The domain's value facts; both variants share one tool schema and state."""
    seeds = importlib.import_module(f"mini_agents.domains.{domain}.seeds")
    return seeds.VALUE_FACTS.to_json()


def render_value_facts(domain: str) -> str:
    return json.dumps(value_facts(domain), indent=2) + "\n"


def read_runtime_spec(path: Path) -> dict[str, Any]:
    """Read a spec this module wrote: JSON under ``#`` comment lines."""
    lines = path.read_text().splitlines()
    return json.loads("\n".join(line for line in lines if not line.startswith("#")))


def rendered() -> dict[Path, str]:
    """Every declaration file, by path, as the generator writes it."""
    files: dict[Path, str] = {}
    for domain in mcp_server.DOMAINS:
        for variant in VARIANTS:
            directory = declaration_dir(domain, variant)
            files[directory / TOOLS_LIST_FILE] = render_tools_list(domain, variant)
            files[directory / RUNTIME_SPEC_FILE] = render_runtime_spec(domain, variant)
            files[directory / VALUE_FACTS_FILE] = render_value_facts(domain)
    return files
