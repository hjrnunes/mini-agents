"""Generate each target's config: how a run starts, resets and stops it.

A target is one domain in one variant. Its config, ``target.yaml`` beside its
declaration files, tells a testing tool everything that tool needs to run the
target without knowing mini-agents: whether it may run at all
(``authorized_as``), where it answers and how to start it (``endpoint``), how to
start its gateway and how the model reaches it (``gateway``), and how to
discover it (``discovery``). The file is JSON under a comment header, as
``runtime-spec.yaml`` is, and YAML reads it unchanged.

The keys follow ``target-v2``: ``schema_version``, ``target``, ``kind``,
``authorized_as``, ``endpoint`` and ``discovery`` carry the same values the
orchestrator's own configs for these targets carry. ``declarations`` is absent
because the declaration files lie beside the config, and ``runtime_contract``
because the contract is built from ``runtime-spec.yaml`` elsewhere. ``gateway``
is the block this repository adds:

- ``port``: where the Responses API answers (``endpoint.agent_url``).
- ``start``: the command that starts the gateway.
- ``env``: how the model endpoint and key reach the gateway, by variable name.
  A value is a placeholder the testing tool fills from its model profile; the
  file never holds a key.

The placeholders are ``{python}``, ``{port}``, ``{mcp_url}``, ``{gateway_port}``,
``{model}``, ``{model_url}`` and ``{model_key}`` (the header below says what
each stands for).

A target's start is its reset: the ledger lives in memory, so a restart gives
the initial ledger, and a gateway keeps its stores in a scratch directory. The
config names no ``health`` or ``reset`` command; a target serves once its port
accepts a connection. A stop is SIGTERM to the started process.

``scripts/gen_declarations.py`` writes these files with the declaration files,
and ``tests/test_declarations.py`` fails while a committed file differs.
"""

from __future__ import annotations

import json
from typing import Any

from mini_agents.kernel.gateway import API_KEY_ENV, BASE_URL_ENV, MODEL_ID_ENV
from mini_agents.kernel.stack import MCP_SERVERS

TARGET_FILE = "target.yaml"
SCHEMA_VERSION = "target-v2"
GATEWAY_PORT = 8321
LOOPBACK = "127.0.0.1"
# The scope each variant's discovery is authorized under. The safe Klarna
# target keeps the id it has always had.
_SCOPE_OVERRIDES = {("klarna", "safe"): "local-test"}

_HEADER = """\
# Generated by scripts/gen_declarations.py from the {domain} stack wiring and
# tool access table ({variant} variant); do not edit. target-v2, written as
# JSON, which YAML reads unchanged.
#
# A run starts, resets and stops the target from this file alone. The commands
# run from this repository's checkout, with these placeholders:
#   {{python}}       the interpreter of the checkout's environment (the gateway
#                  needs the gateway extra)
#   {{port}}         the port the target runs on: endpoint.port, or a free one
#   {{mcp_url}}      endpoint.mcp_url at that port
#   {{gateway_port}} the port the gateway runs on: gateway.port, or a free one
#   {{model}}        the model id of the run's model profile
#   {{model_url}}    the base URL of that profile's endpoint
#   {{model_key}}    that profile's key; this file never holds one
# A start is the reset: the ledger lives in memory, so there is no reset or
# health command, and the target serves once its port accepts a connection.
# Stop either process with SIGTERM.
"""


def target_id(domain: str, variant: str) -> str:
    return domain if variant == "safe" else f"{domain}-{variant}"


def mcp_port(domain: str, variant: str) -> int:
    (port,) = [
        port
        for name, port, unsafe in MCP_SERVERS
        if name == domain and unsafe == (variant == "unsafe")
    ]
    return port


def target_config(
    domain: str, variant: str, operations: dict[str, list[str]]
) -> dict[str, Any]:
    """Return the config of one target; ``operations`` is the runtime spec's."""

    unsafe = variant == "unsafe"
    port = mcp_port(domain, variant)
    scope = _SCOPE_OVERRIDES.get((domain, variant), f"mini{domain}-{variant}-local")
    return {
        "schema_version": SCHEMA_VERSION,
        "target": target_id(domain, variant),
        "kind": "live",
        "authorized_as": "mock",
        "endpoint": {
            "agent_url": f"http://{LOOPBACK}:{GATEWAY_PORT}/v1",
            "mcp_url": f"http://{LOOPBACK}:{{port}}/sse",
            "port": port,
            "start": [
                "{python}",
                "-m",
                "mini_agents",
                "--domain",
                domain,
                "--host",
                LOOPBACK,
                "--port",
                "{port}",
                *(["--unsafe"] if unsafe else []),
            ],
            "start_stage": {"discover": ["--state-summary"]},
            "discover_only_tools": [f"get_{domain}_state_summary"],
            "unset_env": ["MINI_AGENTS_STATE_SUMMARY"],
        },
        "gateway": {
            "port": GATEWAY_PORT,
            "start": [
                "{python}",
                "-m",
                "mini_agents.kernel.gateway",
                "--connector",
                target_id(domain, variant),
                "--mcp-url",
                "{mcp_url}",
                "--port",
                "{gateway_port}",
            ],
            "env": {
                BASE_URL_ENV: "{model_url}",
                API_KEY_ENV: "{model_key}",
                MODEL_ID_ENV: "{model}",
            },
        },
        "discovery": {
            "target_id": f"mini{domain}" + ("-unsafe" if unsafe else ""),
            "authorization_scope_id": scope,
            "read_only_operations": sorted(operations["read_only"]),
            "mutating_operations": sorted(operations["mutating"]),
            "capture": {"query_source": "use_case"},
        },
    }


def render_target_config(
    domain: str, variant: str, operations: dict[str, list[str]]
) -> str:
    header = _HEADER.format(domain=domain, variant=variant)
    config = target_config(domain, variant, operations)
    return header + json.dumps(config, indent=2) + "\n"
